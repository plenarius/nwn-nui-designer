/**
 * The open skin as files: what `pnpm skin ship` writes into assets/skin/ (textures, nui_skin.tml, PROVENANCE.md,
 * LICENSE; the fonts are copied unmodified and checked against tools/open-skin/sources.toml), and the resources of its
 * hak (`pnpm skin hak`). Replaces tools/open-skin/gen_skin.py and build_hak.py (DESIGN.md, "Skin editor").
 */
import { encodeTga32 } from "../../res/tgawrite.js";
import type { ErfEntry } from "../../res/erfwrite.js";
import type { TomlTable } from "../toml.js";
import { writeTml } from "../tmldoc.js";
import { type Style, styleTextures, styleValues } from "./style.js";

/** A font's entry in tools/open-skin/sources.toml. */
export interface FontSource {
  family: string;
  style: string;
  url: string;
  sha256: string;
  copyright: string;
  resref: string;
}

export interface ShipInputs {
  style: Style;
  /** sources.toml's [fonts] table: the style's font key, its display font's (if any) and "jetbrainsmono". */
  fonts: Record<string, FontSource>;
  /** The CC0 1.0 legal code (tools/open-skin/CC0-1.0.txt). */
  cc0: string;
}

const enc = new TextEncoder();

export function fontEntry(name: string, resref: string, spacingH: number, size = 17): TomlTable {
  return { name, resref, pixel_height: 0, pixel_snap: true, oversample_h: 1, oversample_v: 1, font_size: size, spacing_h: spacingH, spacing_v: 0 };
}

/** The sources.toml keys of a style's fonts: its text font, JetBrains Mono, and its display font if it has one. */
export function styleFontKeys(s: Style): string[] {
  return [s.font, "jetbrainsmono", ...(s.display_font ? [s.display_font.font] : [])];
}

/** The open skin's own files (not the fonts and their OFL texts, which are copied as they are). */
export function buildOpenSkin(i: ShipInputs): Record<string, Uint8Array> {
  const s = i.style;
  const all = styleFontKeys(s).map((k) => {
    const f = i.fonts[k];
    if (!f) throw new Error(`sources.toml has no [fonts.${k}]`);
    return f;
  });
  const [main, mono] = all as [FontSource, FontSource];
  const tex = styleTextures(s);
  const out: Record<string, Uint8Array> = {};
  for (const [name, im] of tex) {
    if (name.length > 16) throw new Error(`${name}: resref longer than 16 characters`);
    out[`${name}.tga`] = encodeTga32(im);
  }
  const values = styleValues(s, s.title_body ? "nuio_title" : "nui_windowh");
  const fonts = [fontEntry("(default)", main.resref, s.spacing_h, s.font_size), fontEntry("(monospace)", mono.resref, 0.5)];
  if (s.display_font) fonts.push(fontEntry("display", all[2]!.resref, 0.5, s.display_font.size));
  const names = s.display_font ? `${main.family} ${main.style}, JetBrains Mono and ${all[2]!.family} ${all[2]!.style} ("display")` : `${main.family} ${main.style} and JetBrains Mono`;
  const header =
    `# nwn-nui-designer open skin, preset ${s.key} (${s.title}). Written for this project, not Beamdog's file;\n` +
    `# generated by src/core/skin/gen (pnpm skin ship). Every key the NWN:EE 8193.37 client reads is set.\n` +
    `# This file and the textures: CC0 1.0 (see LICENSE). Fonts: ${names}, SIL OFL 1.1.`;
  out["nui_skin.tml"] = enc.encode(writeTml(values, fonts, header));
  out["PROVENANCE.md"] = enc.encode(provenance(s, all, tex));
  out.LICENSE = enc.encode(licence(all) + i.cc0);
  return out;
}

function licence(fonts: FontSource[]): string {
  return (
    "The nwn-nui-designer open skin\n\n" +
    "nui_skin.tml, every .tga texture and PROVENANCE.md in this folder were made for nwn-nui-designer by its skin\n" +
    "generator (src/core/skin/gen) and are dedicated to the public domain under CC0 1.0 Universal (the legal\n" +
    "code follows). Use them in any module, hak or project, with or without credit.\n\n" +
    "The fonts are NOT covered by CC0. They are unmodified upstream fonts under the SIL Open Font License 1.1:\n" +
    fonts.map((f) => `  ${f.resref}.ttf  ${f.family} ${f.style}, ${f.copyright} (OFL-${f.resref}.txt)\n`).join("") +
    "Keep each OFL-*.txt with its font when you redistribute it.\n\n" +
    "-------------------------------------------------------------------------------\n\n"
  );
}

function provenance(s: Style, fonts: FontSource[], tex: Map<string, { width: number; height: number }>): string {
  const lines = [
    `# nwn-nui-designer open skin (${s.title}): provenance`,
    "",
    s.summary,
    "",
    "## Textures and nui_skin.tml",
    "",
    "Drawn by nwn-nui-designer's skin generator (src/core/skin/gen: draw.ts, style.ts) from the numbers of the " +
      `preset \`${s.key}\`: gradients, seeded value noise, 1 px rims${s.pipe ? ", lit pipes" : ""}${s.rivet ? ", corner rivets" : ""}, glows and antialiased polygons. No input image. ` +
      "The palette was picked by hand for this look; nothing was sampled, traced or derived from Beamdog's textures. " +
      "nui_skin.tml was written by the same generator from the list of keys the client reads " +
      "(src/core/skin/keys.ts); only the key names, the client's interface, are shared with Beamdog's file. Texture " +
      "names follow the game's (nui_windowh, ...) so a hak that replaces one still takes effect; nuio_* names are this " +
      "skin's own. (The generator was first written in Python, tools/open-skin/ until 2026-11-16; the TypeScript port " +
      "draws the same bytes.)",
    "",
    "Licence: CC0 1.0 (LICENSE).",
    "",
    "## Fonts (SIL OFL 1.1, unmodified)",
    "",
  ];
  for (const f of fonts) {
    lines.push(
      `- \`${f.resref}.ttf\`: ${f.family} ${f.style}, ${f.copyright}. From ${f.url} (sha256 ${f.sha256}), unmodified, ` +
        `renamed to its resref only. Licence: OFL-${f.resref}.txt.`,
    );
  }
  lines.push("", "## Files", "");
  for (const [n, im] of [...tex].sort((a, b) => (a[0] < b[0] ? -1 : 1))) lines.push(`- \`${n}.tga\` ${im.width}x${im.height}`);
  return lines.join("\n") + "\n";
}

// --- the hak ------------------------------------------------------------------------------------------------------

/** The hak's description; build_hak.py wrote the Bronze one without the theme's name. */
export function openSkinHakDescription(fonts: FontSource[], theme: string | null): string {
  const names = fonts.map((f) => `${f.family} ${f.style}`).join(" and ");
  return `nwn-nui-designer open skin${theme ? ` "${theme}"` : ""}: nui_skin.tml and textures CC0 1.0, fonts ${names} SIL OFL 1.1 (see the nuio_skin_lic and ofl_* text resources).`;
}

const HAK_TYPES: Record<string, string> = { tga: "tga", txt: "txt", ttf: "ttf", tml: "tml" };
const TEXTS: Record<string, string> = { LICENSE: "nuio_skin_lic", "PROVENANCE.md": "nuio_skin_prov" };

/** A theme folder's files (assets/skin/<theme>) as hak resources, in build_hak.py's order (sorted by file name), the licence texts as .txt. */
export function openSkinHakEntries(files: Record<string, Uint8Array>): ErfEntry[] {
  const out: ErfEntry[] = [];
  const names = Object.keys(files).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  for (const file of names) {
    let name: string;
    let ext: string;
    if (file in TEXTS) [name, ext] = [TEXTS[file]!, "txt"];
    else if (file.startsWith("OFL-") && file.endsWith(".txt")) [name, ext] = [`ofl_${file.slice(4, -4)}`, "txt"];
    else {
      const dot = file.lastIndexOf(".");
      name = file.slice(0, dot);
      ext = file.slice(dot + 1).toLowerCase();
      if (!(ext in HAK_TYPES)) throw new Error(`${file}: not a resource type this hak knows`);
    }
    name = name.toLowerCase();
    if (name.length > 16) throw new Error(`${file}: resref '${name}' is longer than 16 characters`);
    out.push({ resref: name, type: HAK_TYPES[ext]!, data: files[file]! });
  }
  return out;
}
